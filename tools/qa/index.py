"""QA6: writes the indexes a new session reads instead of the whole code.

  debug/TESTS.md    every debug/verify_*.gd: its area, what it checks (its first doc line), how to run it
  docs/CODEMAP.md   every script under core/ and data/: its class and what it is for (first doc line)
  CHANGELOG.md      what changed, newest first, from the commit subjects (the admin panel shows it)

Run from the repository root:  python3 -I tools/qa/index.py
"""
import os, re, subprocess, sys

ROOT = os.getcwd()
AREAS = [  # first match wins: (area, words in the file name)
    ("UI and HUD", ["ui_", "hud", "pager", "phone", "minimap", "map_fog", "next_step", "hustles_paper", "halo", "toast", "moodle", "character_info", "window", "status", "album", "screen", "body_doll", "bag", "hotbar", "store"]),
    ("Police and stealth", ["cop", "case", "stealth", "witness", "sneak", "arrest", "lawyer", "talk"]),
    ("Gangs, rivals and turf", ["rival", "rep_corners", "gang", "turf", "territor", "district", "hood"]),
    ("Crew", ["crew"]),
    ("Crime and combat", ["crime", "combat", "pickpocket", "mug", "burgl", "rob", "loot", "weapon", "gun", "wound", "body_parts", "jobs", "gameplay_feel", "reaction"]),
    ("Economy and money", ["econom", "business", "laundr", "production", "shop", "deal", "wallet", "price", "rank", "skills", "trait"]),
    ("Driving and traffic", ["driv", "traffic", "vehicle", "car"]),
    ("Needs and health", ["need", "stamina", "sleep", "health", "heal"]),
    ("Save and settings", ["save", "autosave", "settings", "play_modes", "bug_report"]),
    ("World, people and navigation", ["sim_", "soak", "nav", "routing", "spawn", "npc", "schedule", "outing", "real_city", "phase", "time", "crowd", "life"]),
    ("3D city and visuals", ["3d", "house", "kit", "render", "door", "window", "palette", "shadow", "light", "night", "street", "player_model", "city"]),
]

def first_doc(path):
    lines = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("##"):
                lines.append(line[2:].strip())
            elif lines:
                break
            elif line.strip() and not line.startswith(("extends", "class_name", "@")):
                break
    text = " ".join(lines)
    return re.sub(r"\s+", " ", text)[:260]

def area_of(name):
    for area, words in AREAS:
        if any(w in name for w in words):
            return area
    return "Other"

def tests():
    rows = {}
    for f in sorted(os.listdir("debug")):
        if f.startswith("verify_") and f.endswith(".gd"):
            name = f[len("verify_"):-3]
            rows.setdefault(area_of(name), []).append((name, first_doc(os.path.join("debug", f))))
    out = ["# Tests (generated by tools/qa/index.py: do not edit by hand)", "",
           "Run one: `$G --headless --path . -s debug/verify_<name>.gd 2>&1 | tail -20`",
           "Run by name filter: `debug/run_all.sh $G <part of a name>` (one filter, no `|`)",
           "Everything: `debug/run_all.sh $G` (slow: run in the background). Pictures: `debug/album.sh $G [regex]`.",
           "In the game: Admin on (pause menu), F11, Tests tab: quick checks on a running game (`core/systems/admin_tests.gd`).", ""]
    total = 0
    for area in [a for a, _ in AREAS] + ["Other"]:
        if area not in rows:
            continue
        out += ["## %s (%d)" % (area, len(rows[area])), "", "| check | what it proves |", "|---|---|"]
        for name, doc in rows[area]:
            out.append("| `%s` | %s |" % (name, doc.replace("|", "/")))
            total += 1
        out.append("")
    out.insert(1, "\n%d checks.\n" % total)
    return "\n".join(out) + "\n"

def codemap():
    out = ["# Code map (generated by tools/qa/index.py: do not edit by hand)", "",
           "One line per script: what it is for. Read the file only when you need it; find symbols with `rg`.", ""]
    for top in ["core", "data"]:
        for d, _, files in sorted(os.walk(top)):
            gd = sorted(f for f in files if f.endswith(".gd"))
            if not gd:
                continue
            out += ["## %s" % d, "", "| file | class | what it is |", "|---|---|---|"]
            for f in gd:
                p = os.path.join(d, f)
                src = open(p, encoding="utf-8").read()
                m = re.search(r"^class_name\s+(\w+)", src, re.M)
                out.append("| `%s` | %s | %s |" % (f, m.group(1) if m else "", first_doc(p).replace("|", "/")))
            out.append("")
    return "\n".join(out) + "\n"

def changelog():
    try:
        log = subprocess.run(["git", "log", "--no-merges", "--date=short", "--format=%ad\t%s", "-n", "300"], capture_output=True, text=True, check=True).stdout
    except Exception as e:
        return "# Changelog\n\n(git log not available: %s)\n" % e
    out = ["# Changelog (generated by tools/qa/index.py from the commit subjects)", "", "Newest first. The in-game admin panel (F11, Bugs & updates) shows the top of it.", ""]
    day = None
    for line in log.splitlines():
        if "\t" not in line:
            continue
        d, s = line.split("\t", 1)
        if d != day:
            out += ["", "## " + d, ""]
            day = d
        out.append("- " + s)
    return "\n".join(out) + "\n"

if __name__ == "__main__":
    for path, text in [("debug/TESTS.md", tests()), ("docs/CODEMAP.md", codemap()), ("CHANGELOG.md", changelog())]:
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote", path, len(text.splitlines()), "lines")
